#!/bin/bash
# Linux/make-shims.sh - (re)generates Linux/Targets/<target>/, the source folders of the Linux
# build's targets (Package.swift), from Linux/sources.txt.
#
# Each line of sources.txt names a target and a source file (path from the repository root). The
# script writes Linux/Targets/<target>/<file name>.c (for a .c source) or .cpp (for .cpp and
# the C++-only .mm), holding one #include of the real file. SwiftPM then compiles every source in
# place under a name it recognizes (it would build .mm as Objective-C++). The real files stay
# where the Xcode projects have them.
#
# Usage: Linux/make-shims.sh            (run from anywhere; no arguments)
# Exit status: 0 done, 1 an error (named on stderr).

here="$(CDPATH= cd -P -- "$(/usr/bin/dirname "$0")" && pwd)"
repo="$(CDPATH= cd -P -- "$here/.." && pwd)"
list="$here/sources.txt"
targets="$here/Targets"

if [ ! -f "$list" ]; then
    printf 'make-shims: no source list at %s\n' "$list" >&2
    exit 1
fi

# Start from nothing, so a source taken off the list loses its shim. Only this script writes there.
# The old folder is set aside and an unchanged shim is moved back rather than rewritten: a new
# modification date would make every build recompile every source.
old_targets="$here/Targets.old"
if [ -d "$old_targets" ]; then
    /bin/rm -rf "$old_targets"
    status=$?
    if [ "$status" -ne 0 ]; then
        printf 'make-shims: cannot remove %s\n' "$old_targets" >&2
        exit 1
    fi
fi
if [ -d "$targets" ]; then
    /bin/mv "$targets" "$old_targets"
    status=$?
    if [ "$status" -ne 0 ]; then
        printf 'make-shims: cannot move the old %s aside\n' "$targets" >&2
        exit 1
    fi
fi

count=0
line_number=0
while IFS= read -r line || [ -n "$line" ]; do
    line_number=$((line_number + 1))
    case "$line" in
        ''|'#'*) continue ;;
    esac
    target="${line%% *}"
    source="${line#* }"
    if [ -z "$target" ] || [ -z "$source" ] || [ "$target" = "$line" ]; then
        printf 'make-shims: %s:%s: expected "<target> <path>": %s\n' "$list" "$line_number" "$line" >&2
        exit 1
    fi
    if [ ! -f "$repo/$source" ]; then
        printf 'make-shims: %s:%s: no such file: %s\n' "$list" "$line_number" "$source" >&2
        exit 1
    fi
    name="$(/usr/bin/basename "$source")"
    case "$source" in
        *.c) shim="${name%.c}.c" ;;
        *.cpp) shim="$name" ;;
        *.mm) shim="${name%.mm}.cpp" ;;
        *)
            printf 'make-shims: %s:%s: not a C or C++ source: %s\n' "$list" "$line_number" "$source" >&2
            exit 1
            ;;
    esac
    folder="$targets/$target"
    /bin/mkdir -p "$folder"
    status=$?
    if [ "$status" -ne 0 ]; then
        printf 'make-shims: cannot create %s\n' "$folder" >&2
        exit 1
    fi
    if [ -e "$folder/$shim" ]; then
        printf 'make-shims: %s:%s: two sources of %s give the same shim name %s\n' "$list" "$line_number" "$target" "$shim" >&2
        exit 1
    fi
    # Linux/Targets/<target>/ is three folders below the repository root
    printf -v text '// Generated by Linux/make-shims.sh from Linux/sources.txt: do not edit.\n#include "../../../%s"' "$source"
    old_shim="$old_targets/$target/$shim"
    if [ -f "$old_shim" ] && [ "$(< "$old_shim")" = "$text" ]; then
        /bin/mv "$old_shim" "$folder/$shim"
        status=$?
    else
        printf '%s\n' "$text" > "$folder/$shim"
        status=$?
    fi
    if [ "$status" -ne 0 ]; then
        printf 'make-shims: cannot write %s\n' "$folder/$shim" >&2
        exit 1
    fi
    count=$((count + 1))
done < "$list"

if [ -d "$old_targets" ]; then
    /bin/rm -rf "$old_targets"
    status=$?
    if [ "$status" -ne 0 ]; then
        printf 'make-shims: cannot remove %s\n' "$old_targets" >&2
        exit 1
    fi
fi

printf 'make-shims: %s shims in %s\n' "$count" "$targets"
exit 0
